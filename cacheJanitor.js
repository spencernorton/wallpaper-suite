// Conservative age-based maintenance for Wallpaper Suite's private cache.
//
// The janitor enumerates one exact directory and accepts only filenames that
// this version of Wallpaper Suite can generate. It never uses wildcard/glob
// deletion, follows no symlinks, and protects every active or in-flight path.

import Gio from 'gi://Gio';
import GLib from 'gi://GLib';

export const DEFAULT_TEMP_MAX_AGE_SECONDS = 24 * 60 * 60;
export const DEFAULT_OUTPUT_MAX_AGE_SECONDS = 30 * 24 * 60 * 60;

const UUID_PATTERN = '[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}';
const OUTPUT_BASENAME_PATTERN =
    `composite-(?:[a-f0-9]{8}|[a-f0-9]{32}(?:-refresh-${UUID_PATTERN}-\\d+)?)\\.jpg`;
const OUTPUT_RE = new RegExp(`^${OUTPUT_BASENAME_PATTERN}$`);
const SIDECAR_RE = new RegExp(`^(${OUTPUT_BASENAME_PATTERN})\\.meta\\.json$`);
const OUTPUT_TEMP_RE = new RegExp(
    `^(${OUTPUT_BASENAME_PATTERN})\\.tmp\\.${UUID_PATTERN}\\.(?:\\d+|sync)$`);
const SIDECAR_TEMP_RE = new RegExp(
    `^(${OUTPUT_BASENAME_PATTERN})\\.meta\\.json\\.tmp\\.${UUID_PATTERN}\\.\\d+$`);
const STATUS_TEMP_RE = new RegExp(`^runtime-status\\.json\\.tmp\\.${UUID_PATTERN}$`);

/** Classify only cache filenames generated by Wallpaper Suite. */
export function classifyManagedCacheName(name) {
    if (typeof name !== 'string' || !name)
        return null;
    if (OUTPUT_RE.test(name))
        return {kind: 'output', outputName: name};

    let match = SIDECAR_RE.exec(name);
    if (match)
        return {kind: 'sidecar', outputName: match[1]};
    match = OUTPUT_TEMP_RE.exec(name);
    if (match)
        return {kind: 'temp', outputName: match[1]};
    match = SIDECAR_TEMP_RE.exec(name);
    if (match)
        return {kind: 'temp', outputName: match[1]};
    if (STATUS_TEMP_RE.test(name))
        return {kind: 'temp', outputName: null};
    return null;
}

/**
 * Remove stale managed cache entries by exact path.
 *
 * `protectedPaths` should contain all light/dark/lock-screen and in-flight
 * paths. Output protection automatically covers its sidecar and vice versa.
 */
export function pruneManagedCache(cacheDir, protectedPaths = new Set(), options = {}) {
    const result = {examined: 0, removed: [], errors: []};
    const nowUsec = Number.isFinite(options.nowUsec)
        ? Number(options.nowUsec)
        : GLib.get_real_time();
    const tempMaxAgeUsec = _ageUsec(
        options.tempMaxAgeSeconds, DEFAULT_TEMP_MAX_AGE_SECONDS);
    const outputMaxAgeUsec = _ageUsec(
        options.outputMaxAgeSeconds, DEFAULT_OUTPUT_MAX_AGE_SECONDS);
    const canonicalDir = _canonical(cacheDir);
    const protectedNames = _protectedNames(canonicalDir, protectedPaths);
    const entries = new Map();

    let enumerator = null;
    try {
        enumerator = Gio.File.new_for_path(canonicalDir).enumerate_children(
            'standard::name,standard::type,time::modified,time::modified-usec',
            Gio.FileQueryInfoFlags.NOFOLLOW_SYMLINKS,
            null
        );
        let info;
        while ((info = enumerator.next_file(null)) !== null) {
            const name = info.get_name();
            const classification = classifyManagedCacheName(name);
            if (!classification || info.get_file_type() !== Gio.FileType.REGULAR)
                continue;
            result.examined++;
            entries.set(name, {
                name,
                path: GLib.build_filenamev([canonicalDir, name]),
                classification,
                modifiedUsec:
                    Number(info.get_attribute_uint64('time::modified')) * 1e6 +
                    info.get_attribute_uint32('time::modified-usec'),
            });
        }
    } catch (error) {
        result.errors.push(`Cannot enumerate ${canonicalDir}: ${error}`);
        return result;
    } finally {
        try { enumerator?.close(null); } catch (_) {}
    }

    const removedNames = new Set();
    const remove = entry => {
        if (!entry || removedNames.has(entry.name) || protectedNames.has(entry.name))
            return false;
        try {
            Gio.File.new_for_path(entry.path).delete(null);
            removedNames.add(entry.name);
            result.removed.push(entry.path);
            return true;
        } catch (error) {
            result.errors.push(`Cannot remove ${entry.path}: ${error}`);
            return false;
        }
    };
    const oldEnough = (entry, maxAgeUsec) =>
        nowUsec >= entry.modifiedUsec && nowUsec - entry.modifiedUsec >= maxAgeUsec;

    // Generation/status temporaries are never valid publication targets.
    for (const entry of entries.values()) {
        if (entry.classification.kind === 'temp' && oldEnough(entry, tempMaxAgeUsec))
            remove(entry);
    }

    // Delete an old unreferenced output and only its exact matching sidecar.
    for (const entry of entries.values()) {
        if (entry.classification.kind !== 'output' ||
            !oldEnough(entry, outputMaxAgeUsec) || protectedNames.has(entry.name))
            continue;
        if (remove(entry))
            remove(entries.get(`${entry.name}.meta.json`));
    }

    // A sidecar whose exact output is absent is independently disposable once
    // old. Sidecars for live outputs are retained regardless of sidecar mtime.
    for (const entry of entries.values()) {
        if (entry.classification.kind !== 'sidecar' ||
            !oldEnough(entry, outputMaxAgeUsec))
            continue;
        const outputName = entry.classification.outputName;
        const outputStillExists = entries.has(outputName) && !removedNames.has(outputName);
        if (!outputStillExists)
            remove(entry);
    }

    return result;
}

function _ageUsec(value, fallbackSeconds) {
    const seconds = Number.isFinite(value) && value >= 0 ? Number(value) : fallbackSeconds;
    return seconds * 1e6;
}

function _canonical(path) {
    try { return GLib.canonicalize_filename(path, null); } catch (_) { return path; }
}

function _protectedNames(cacheDir, paths) {
    const names = new Set();
    for (const path of paths || []) {
        if (!path || _canonical(GLib.path_get_dirname(path)) !== cacheDir)
            continue;
        const name = GLib.path_get_basename(path);
        const classification = classifyManagedCacheName(name);
        if (!classification)
            continue;
        names.add(name);
        if (classification.kind === 'output')
            names.add(`${name}.meta.json`);
        else if (classification.kind === 'sidecar')
            names.add(classification.outputName);
    }
    return names;
}
